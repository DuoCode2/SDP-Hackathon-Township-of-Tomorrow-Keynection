"""Write the WhatsApp message templates SDP submits to Meta, from the alert texts the app already uses.

WhatsApp Business only sends a business-started message from a template Meta has approved: fixed text with numbered
variables ({{1}}, {{2}}...), one per language, with sample values. These are the same alerts the app shows in its
WhatsApp preview and sends as phone notifications in a pilot, so the two never drift apart. Run from
prototype/backend:
    .venv/Scripts/python scripts/export_whatsapp_templates.py
"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from app import talk  # noqa: E402

OUT = Path(__file__).resolve().parents[2] / "docs" / "whatsapp-templates.md"
META_LANG = {"en": "en", "ms": "ms", "zh": "zh_CN", "ta": "ta"}
SAMPLES = {
    "name": "Siti", "label": "No. 11", "scope": "Kitchen extension", "start": "15 Oct", "end": "30 Oct",
    "hours": "Mon–Sat 9:00–18:00", "quiet": "These hours avoid your quiet time.", "contractor": "ABC Renovation",
    "category": "Noise outside the agreed hours", "note": "Contractor reminded about the hours", "title": "Water cut",
    "body": "Tomorrow 9am to noon", "subject": "Crack on the shared wall",
}
BUTTONS = {  # quick replies each alert offers in the app's WhatsApp preview
    "reno": ("open", "concern"), "hello": ("wave",), "message": ("open",), "voice": ("open",), "wave": ("wave",),
    "request": ("accept",), "concern_new": ("open",), "concern_reply": ("open",), "concern_sorted": ("open",),
    "concern_estate_raiser": ("open",), "concern_estate_owner": ("open",), "concern_closed": ("open",),
    "notice": ("open",), "reno_photo": ("photo",), "reno_done": ("all_good", "changed"), "reno_done_owner": ("open",),
    "repair": ("open",),
}


def numbered(text: str) -> tuple[str, list[str]]:
    """Meta wants {{1}}, {{2}}... in order, text before the first variable and after the last."""
    names: list[str] = []

    def number(m: re.Match) -> str:
        if m.group(1) not in names:
            names.append(m.group(1))
        return "{{" + str(names.index(m.group(1)) + 1) + "}}"

    body = re.sub(r"\{(\w+)\}", number, text)
    return f"Keynection: {body}" + ("" if re.search(r"[.!?。！？👋]$", body) else "."), names


def main() -> None:
    lines = [
        "# WhatsApp message templates for Keynection",
        "",
        "Generated by `backend/scripts/export_whatsapp_templates.py` from the alert texts in `backend/app/talk.py`;",
        "regenerate after changing them. For SDP's WhatsApp Business account (Meta Business Manager → WhatsApp →",
        "Message templates). Category: **Utility** for all of them. Each language is a separate template version.",
        "",
        "Before sending through WhatsApp, Keynection also needs each owner's mobile number, given by the owner with",
        "consent and checked with a one-time code, and SDP's access token in the server's settings. Until then the",
        "same alerts go out as phone notifications (web push) and show in the app's WhatsApp preview.",
        "",
        "- A chat alert never contains what was written: only who wrote, and a reminder to open Keynection.",
        "- `{{n}}` must never be empty: where the app leaves a part out (the quiet-time note), send \"-\".",
        "- The numbers follow each language's own word order (in Chinese the house comes before the name), so the",
        "  sender fills them per language, as listed in the last column.",
        "- Tamil (`ta`) needs a native speaker's review before submitting.",
        "",
    ]
    for key, versions in talk.WA_TEMPLATES.items():
        lines += [f"## keynection_{key}", ""]
        _, names = numbered(versions["en"])
        if names:
            lines += ["Samples: " + ", ".join(f"{n} “{SAMPLES[n]}”" for n in names), ""]
        buttons = BUTTONS.get(key, ())
        if buttons:
            lines += ["Quick-reply buttons: " + "; ".join(" / ".join(talk.wa_button(b, lang) for lang in META_LANG) for b in buttons), ""]
        lines += ["| Language | Body | Variables, in this language's order |", "|---|---|---|"]
        for lang, code in META_LANG.items():
            if lang in versions:
                body, order = numbered(versions[lang])
                numbers = ", ".join(f"{{{{{i + 1}}}}} {n}" for i, n in enumerate(order)) or "none"
                lines.append(f"| `{code}` | {body.replace('|', '/')} | {numbers} |")
        lines.append("")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(talk.WA_TEMPLATES)} templates written to {OUT}")


if __name__ == "__main__":
    main()
